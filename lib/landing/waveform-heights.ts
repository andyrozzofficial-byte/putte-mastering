/** Integer percent height for stable inline styles (SSR-safe). */
export function waveformBarHeightPercent(h: number): number {
  return Math.round(h * 100);
}

/** CSS custom property for subtle live pulse — derived from frozen height. */
export function waveformBarPulseScale(h: number): string {
  const pulse = 1 + Math.round(h * 100) / 1000;
  return pulse.toFixed(3);
}
